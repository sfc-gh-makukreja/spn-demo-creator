-- One-time setup for the CoWork demo creator. Run as ACCOUNTADMIN.
-- Edit the names below if you want something other than the defaults.

CREATE DATABASE IF NOT EXISTS COWORK_DEMOS;
CREATE SCHEMA IF NOT EXISTS COWORK_DEMOS.PUBLIC;

CREATE WAREHOUSE IF NOT EXISTS COWORK_DEMO_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Cross-region inference, only if your region lacks the orchestration model.
-- ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- Optional: email tool. Recipients must be verified email addresses in the account.
CREATE NOTIFICATION INTEGRATION IF NOT EXISTS COWORK_DEMO_EMAIL
  TYPE = EMAIL
  ENABLED = TRUE;

CREATE OR REPLACE PROCEDURE COWORK_DEMOS.PUBLIC.SEND_MAIL(
  RECIPIENT VARCHAR, SUBJECT VARCHAR, BODY VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
BEGIN
  CALL SYSTEM$SEND_EMAIL('COWORK_DEMO_EMAIL', :RECIPIENT, :SUBJECT, :BODY, 'text/html');
  RETURN 'Email sent to ' || :RECIPIENT;
END;

