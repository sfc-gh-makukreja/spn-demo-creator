-- Optional roles for sharing a demo. Run as a role that can create roles (for example USERADMIN or SECURITYADMIN).
-- Replace <DATABASE>, <SCHEMA>, <WAREHOUSE>, <AGENT_SCHEMA_DB>, <AGENT_SCHEMA>, <USER>.

CREATE ROLE IF NOT EXISTS COWORK_DEMO_ADMIN;
GRANT USAGE ON DATABASE <DATABASE> TO ROLE COWORK_DEMO_ADMIN;
GRANT USAGE ON SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_ADMIN;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_ADMIN;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_ADMIN;
GRANT USAGE ON WAREHOUSE <WAREHOUSE> TO ROLE COWORK_DEMO_ADMIN;

CREATE ROLE IF NOT EXISTS COWORK_DEMO_USER;
GRANT USAGE ON DATABASE <DATABASE> TO ROLE COWORK_DEMO_USER;
GRANT USAGE ON SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_USER;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA <DATABASE>.<SCHEMA> TO ROLE COWORK_DEMO_USER;
GRANT USAGE ON WAREHOUSE <WAREHOUSE> TO ROLE COWORK_DEMO_USER;
